//! recipe-static-binary-part: `lpoco-bringup image ensure NAME` for a `[part_builds.NAME]` builds a static aarch64
//! binary from a crate at a git commit in Nix's sandbox as a fixed-output derivation (decisions
//! 2026-11-23-image-recipes-on-nix-fixed-output-paths and 2026-11-24-a-recipe-sha-is-proved-by-a-rebuild).
//! The crate here is a stand-in with no dependencies and one unit test; the compiler, the std library built from
//! source (-Zbuild-std), the cross linker and the static glibc are the real ones of the pinned nixpkgs. Where nix is
//! absent the test says "not measured".
//! The expected sha256 is not read back from a build of this run: it was taken once from the "hash mismatch" Nix
//! printed for a zero sha256 (2026-11-27, bringup/src/part.nix), and a later run, in another folder with another
//! commit, built the same bytes under it and `nix-build --check` found them again; it holds for any path and any
//! commit that carries the same three crate files. The file's kind is read from its ELF header, never from the
//! build's own say-so.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

const CARGO_TOML: &str =
    "[package]\nname = \"standin\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[[bin]]\nname = \"standin\"\npath = \"src/main.rs\"\n";
const CARGO_LOCK: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"standin\"\nversion = \"0.1.0\"\n";
const MAIN_RS: &str = "fn word() -> &'static str { \"part\" }\nfn main() { println!(\"{}\", word()); }\n#[cfg(test)]\nmod t { #[test] fn w() { assert_eq!(super::word(), \"part\"); } }\n";
/// The sha256 of the binary those four files make (taken once from Nix's hash mismatch; see the header)
const MEASURED: &str = "719d74cbdf23510300a968976624a9e7bda944646f1610e5064dbde0b8c60161";

fn tmp(name: &str) -> PathBuf {
    let d = std::env::temp_dir().join(format!(
        "lpoco-bringup-ensure-part-{}-{name}",
        std::process::id()
    ));
    let _ = fs::remove_dir_all(&d);
    fs::create_dir_all(&d).unwrap();
    d
}

fn text(b: &[u8]) -> String {
    String::from_utf8_lossy(b).into_owned()
}

fn run(dir: &Path, tool: &str, args: &[&str]) -> String {
    let o = Command::new(tool)
        .current_dir(dir)
        .args(args)
        .output()
        .unwrap();
    assert!(o.status.success(), "{tool} {args:?}: {}", text(&o.stderr));
    text(&o.stdout).trim().to_string()
}

fn has_nix() -> bool {
    Command::new("nix-store")
        .arg("--version")
        .output()
        .is_ok_and(|o| o.status.success())
}

/// A git repo holding the stand-in crate under `crates/standin` (the crate is not at the repo's root, as
/// walleye's tools/walleye-reboot is not); returns its commit.
fn repo(dir: &Path, main_rs: &str) -> String {
    let krate = dir.join("crates/standin");
    fs::create_dir_all(krate.join("src")).unwrap();
    fs::write(krate.join("Cargo.toml"), CARGO_TOML).unwrap();
    fs::write(krate.join("Cargo.lock"), CARGO_LOCK).unwrap();
    fs::write(krate.join("src/main.rs"), main_rs).unwrap();
    let g = |a: &[&str]| run(dir, "git", a);
    g(&["init", "-q", "-b", "main"]);
    g(&["add", "."]);
    g(&[
        "-c",
        "user.name=t",
        "-c",
        "user.email=t@t",
        "commit",
        "-q",
        "-m",
        "standin",
    ]);
    g(&["rev-parse", "HEAD"])
}

fn manifest(dir: &Path, repo: &Path, rev: &str, sha: &str) -> PathBuf {
    let base = fs::read_to_string(
        Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/device.toml"),
    )
    .unwrap();
    let p = dir.join("device.toml");
    fs::write(
        &p,
        format!(
            "{base}\n[part_builds.standin]\nrepo = \"file://{}\"\nrev = \"{rev}\"\ncrate = \"crates/standin\"\nbin = \"standin\"\nsha256 = \"{sha}\"\n",
            repo.display()
        ),
    )
    .unwrap();
    p
}

fn ensure(device: &Path, extra: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_lpoco-bringup"))
        .args(["image", "ensure", "standin", "--device"])
        .arg(device)
        .args(extra)
        .output()
        .unwrap()
}

/// A path an earlier run left in the store would be served, not built: the test starts without it.
fn forget(dir: &Path, sha: &str) {
    let stored = run(
        dir,
        "nix-store",
        &[
            "--print-fixed-path",
            "sha256",
            sha,
            &format!("part-{}", &sha[..12]),
        ],
    );
    let _ = Command::new("nix-store")
        .args(["--delete", &stored])
        .output();
}

/// (machine, has an interpreter): from the ELF header and its program headers, 64-bit little-endian files only.
fn elf(bytes: &[u8]) -> (u16, bool) {
    assert_eq!(&bytes[..4], b"\x7fELF", "not an ELF file");
    assert_eq!(
        (bytes[4], bytes[5]),
        (2, 1),
        "not a 64-bit little-endian ELF"
    );
    let u16_at = |o: usize| u16::from_le_bytes(bytes[o..o + 2].try_into().unwrap());
    let u32_at = |o: usize| u32::from_le_bytes(bytes[o..o + 4].try_into().unwrap());
    let u64_at = |o: usize| u64::from_le_bytes(bytes[o..o + 8].try_into().unwrap()) as usize;
    let (phoff, phentsize, phnum) = (u64_at(32), u16_at(54) as usize, u16_at(56) as usize);
    // PT_INTERP is program header type 3: a dynamically linked file names its loader there
    let interp = (0..phnum).any(|i| u32_at(phoff + i * phentsize) == 3);
    (u16_at(18), interp)
}

#[test]
fn a_part_is_built_static_for_aarch64_from_its_commit_held_to_its_sha256_and_served_from_the_store_after(
) {
    if !has_nix() {
        eprintln!("not measured: no nix");
        return;
    }
    let dir = tmp("p");
    let repo_dir = dir.join("tools");
    fs::create_dir_all(&repo_dir).unwrap();
    let rev = repo(&repo_dir, MAIN_RS);
    forget(&dir, MEASURED);
    let device = manifest(&dir, &repo_dir, &rev, MEASURED);

    let o = ensure(&device, &[]);
    assert!(
        o.status.success(),
        "ensure (build): {}{}",
        text(&o.stdout),
        text(&o.stderr)
    );
    let path = text(&o.stdout).trim().to_string();
    let bytes = fs::read(&path).unwrap();
    let (machine, interp) = elf(&bytes);
    assert_eq!(machine, 0xb7, "EM_AARCH64 is 183 (0xb7)");
    assert!(!interp, "the binary names a loader: it is not static");
    assert!(
        text(&bytes)
            .split("/nix/store/")
            .skip(1)
            .all(|rest| rest.starts_with(&"e".repeat(32))),
        "a store path with a real hash is left in a file that runs on a phone"
    );
    assert!(
        text(&o.stderr).contains("standin: built from its recipe"),
        "{}",
        text(&o.stderr)
    );

    // served by its sha256 the second time: nothing runs
    let o = ensure(&device, &[]);
    assert!(
        text(&o.stderr).contains("in the store") && !text(&o.stderr).contains("built"),
        "{}",
        text(&o.stderr)
    );

    // proved by a rebuild: --rebuild ignores the store and says the bytes are equal
    let o = ensure(&device, &["--rebuild"]);
    assert!(
        o.status.success() && text(&o.stderr).contains("rebuilt from its recipe, equal"),
        "{}{}",
        text(&o.stdout),
        text(&o.stderr)
    );
}

#[test]
fn a_part_whose_commit_does_not_make_the_declared_sha256_fails_naming_the_part() {
    if !has_nix() {
        eprintln!("not measured: no nix");
        return;
    }
    let dir = tmp("w");
    let repo_dir = dir.join("tools");
    fs::create_dir_all(&repo_dir).unwrap();
    let rev = repo(&repo_dir, MAIN_RS);
    let wrong = "0".repeat(64);
    forget(&dir, &wrong);
    let o = ensure(&manifest(&dir, &repo_dir, &rev, &wrong), &[]);
    let said = text(&o.stderr);
    assert!(
        !o.status.success(),
        "a part that is not the declared sha256 passed"
    );
    assert!(said.contains("standin"), "the part is not named: {said}");
    assert!(
        said.contains("hash mismatch"),
        "refused for another reason than the hash: {said}"
    );
}

#[test]
fn a_part_whose_unit_test_fails_is_not_built() {
    if !has_nix() {
        eprintln!("not measured: no nix");
        return;
    }
    let dir = tmp("t");
    let repo_dir = dir.join("tools");
    fs::create_dir_all(&repo_dir).unwrap();
    let rev = repo(
        &repo_dir,
        &MAIN_RS.replace(
            "assert_eq!(super::word(), \"part\")",
            "assert_eq!(super::word(), \"other\")",
        ),
    );
    let sha = "1".repeat(64);
    forget(&dir, &sha);
    let o = ensure(&manifest(&dir, &repo_dir, &rev, &sha), &[]);
    let said = text(&o.stderr);
    assert!(
        !o.status.success(),
        "a part with a failing unit test was built"
    );
    assert!(said.contains("standin"), "the part is not named: {said}");
    assert!(
        said.contains("test result: FAILED") || said.contains("panicked"),
        "stopped for another reason than the unit test: {said}"
    );
}

/// The sha256 of the pinned nixpkgs' static aarch64 busybox 1.37.0 (musl) at bin/busybox, its one store path scrubbed
/// as a part's is. Taken once from the "hash mismatch" Nix printed for a zero sha256 (2026-11-27, bringup/src/part.nix),
/// not from a build of this run; the test's `--rebuild` finds the same bytes again.
const BUSYBOX: &str = "7593d31b555f67d197296966c05f8474be4e8f073ff4e39ba72aa50476d32ad2";

#[test]
fn a_part_of_a_nixpkgs_program_is_its_static_aarch64_build_held_to_its_sha256_and_proved_by_a_rebuild(
) {
    if !has_nix() {
        eprintln!("not measured: no nix");
        return;
    }
    let dir = tmp("n");
    forget(&dir, BUSYBOX);
    let base = fs::read_to_string(
        Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/device.toml"),
    )
    .unwrap();
    let device = dir.join("device.toml");
    fs::write(
        &device,
        format!(
            "{base}\n[part_builds.busybox]\nnixpkgs = \"busybox\"\nbin = \"busybox\"\nsha256 = \"{BUSYBOX}\"\n"
        ),
    )
    .unwrap();
    let run_ensure = |extra: &[&str]| {
        Command::new(env!("CARGO_BIN_EXE_lpoco-bringup"))
            .args(["image", "ensure", "busybox", "--device"])
            .arg(&device)
            .args(extra)
            .output()
            .unwrap()
    };
    let o = run_ensure(&[]);
    assert!(
        o.status.success(),
        "ensure (build): {}{}",
        text(&o.stdout),
        text(&o.stderr)
    );
    let bytes = fs::read(text(&o.stdout).trim()).unwrap();
    let (machine, interp) = elf(&bytes);
    assert_eq!(machine, 0xb7, "EM_AARCH64 is 183 (0xb7)");
    assert!(!interp, "the binary names a loader: it is not static");
    assert!(
        text(&bytes)
            .split("/nix/store/")
            .skip(1)
            .all(|rest| rest.starts_with(&"e".repeat(32))),
        "a store path with a real hash is left in a file that runs on a phone"
    );
    let o = run_ensure(&["--rebuild"]);
    assert!(
        o.status.success() && text(&o.stderr).contains("rebuilt from its recipe, equal"),
        "{}{}",
        text(&o.stdout),
        text(&o.stderr)
    );
}
